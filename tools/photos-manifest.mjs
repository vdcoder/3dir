#!/usr/bin/env node
// After `meshy image` runs: makes 3D-wall thumbnails and writes
// src/data/photos.ts (canonical path -> public image path).
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const list = JSON.parse(readFileSync(join(ROOT, 'assets-src/meshy/photo-list.json'), 'utf8'))
mkdirSync(join(ROOT, 'public/photos/thumbs'), { recursive: true })
const entries = []
for (const p of list) {
  const full = join(ROOT, 'public/photos', `${p.slug}.webp`)
  if (!existsSync(full)) continue
  const thumb = join(ROOT, 'public/photos/thumbs', `${p.slug}.webp`)
  if (!existsSync(thumb)) {
    execFileSync('python3', ['-I', '-c', `
from PIL import Image
im = Image.open(${JSON.stringify(full)}).convert('RGB')
im.thumbnail((320, 320))
im.save(${JSON.stringify(thumb)}, 'WEBP', quality=78)
`])
  }
  entries.push([p.path, p.slug])
}
const body = entries.map(([path, slug]) => `  ${JSON.stringify(path)}: ${JSON.stringify(slug)},`).join('\n')
writeFileSync(join(ROOT, 'src/data/photos.ts'), `// Generated by tools/photos-manifest.mjs. Canonical path -> image slug in public/photos/
// (full size: photos/<slug>.webp, 3D wall thumbnail: photos/thumbs/<slug>.webp).
export const PHOTOS: Record<string, string> = {
${body}
}
`)
console.log(`${entries.length} photos in manifest`)
